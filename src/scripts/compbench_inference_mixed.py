"""Run CompBench mixed-prompt inference from the command line."""

from __future__ import annotations

import argparse
import os
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from framework.inference import ModelPool


def _parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Run MixedPrompt mixed-prompt inference on CompBench annotations."
    )
    annotation_group = parser.add_mutually_exclusive_group()
    annotation_group.add_argument(
        "--annotations",
        type=Path,
        help="Annotation JSONL path; defaults to the latest CompBench annotation run.",
    )
    annotation_group.add_argument(
        "--annotation-run",
        help="CompBench annotation run name (run_<timestamp>) or 'latest'.",
    )
    parser.add_argument(
        "--output-root",
        type=Path,
        help=(
            "Output root; the 'mixed' subdirectory is appended. "
            "Defaults to .out/evaluation/compbench."
        ),
    )
    parser.add_argument(
        "--limit",
        type=int,
        help="Process at most this many selected annotations, starting at --start-index.",
    )
    selection_group = parser.add_mutually_exclusive_group()
    selection_group.add_argument(
        "--tasks",
        nargs="+",
        metavar="TASK",
        help=(
            "Only run these CompBench metadata.task values (for example: "
            "--tasks add replace). Defaults to all tasks."
        ),
    )
    selection_group.add_argument(
        "--samples-file",
        type=Path,
        help=(
            "Run only the CompBench metadata.row_index values listed in a text "
            "file, such as one generated by scripts.compbench_incomplete_samples."
        ),
    )
    parser.add_argument(
        "--start-index",
        type=int,
        default=0,
        help="First annotation index to process (default: 0).",
    )
    parser.add_argument(
        "--resume",
        action="store_true",
        help="Resume an existing evaluation run, skipping completed samples.",
    )
    parser.add_argument(
        "--run",
        help="Existing run_<timestamp> to resume; defaults to the latest run.",
    )
    parser.add_argument(
        "--rerun-completed",
        action="store_true",
        help=(
            "With --resume, rerun every selected sample after removing its old logs "
            "and generated images."
        ),
    )
    parser.add_argument(
        "--require-cuda",
        action="store_true",
        help="Fail before model loading if PyTorch cannot access a CUDA GPU.",
    )
    from evaluation.first_turn import add_first_turn_arguments

    add_first_turn_arguments(parser)
    args = parser.parse_args(argv)

    if args.limit is not None and args.limit < 1:
        parser.error("--limit must be greater than zero.")
    if args.start_index < 0:
        parser.error("--start-index must be zero or greater.")
    if args.samples_file and (args.start_index != 0 or args.limit is not None):
        parser.error("--samples-file cannot be combined with --start-index or --limit.")
    if args.run and not args.resume:
        parser.error("--run can only be used with --resume.")
    if args.rerun_completed and not args.resume:
        parser.error("--rerun-completed can only be used with --resume.")
    if args.annotations and args.annotation_run:
        parser.error("--annotations and --annotation-run cannot be combined.")
    return args


def _resolve_launch_path(path: Path) -> Path:
    launch_dir = Path(os.environ.get("EVAL_START_DIR") or Path.cwd()).resolve()
    path = path.expanduser()
    return path.resolve() if path.is_absolute() else (launch_dir / path).resolve()


def main(argv: list[str] | None = None, pool: ModelPool | None = None) -> None:
    args = _parse_args(argv)

    from framework.utils.project import load_project_environment

    load_project_environment()

    if args.annotations:
        os.environ["MIXED_PROMPT_COMPBENCH_ANNOTATIONS"] = str(
            _resolve_launch_path(args.annotations)
        )
    if args.annotation_run:
        os.environ["MIXED_PROMPT_COMPBENCH_ANNOTATIONS"] = ""
        os.environ["MIXED_PROMPT_COMPBENCH_ANNOTATION_RUN"] = args.annotation_run
    if args.output_root:
        os.environ["MIXED_PROMPT_COMPBENCH_OUTPUT_DIR"] = str(
            _resolve_launch_path(args.output_root)
        )

    from evaluation.common import run_benchmark
    from evaluation.first_turn import build_first_turn_config, build_from_run
    from evaluation.compbench_incomplete import read_sample_indices
    from evaluation.compbench_selection import select_compbench_indices
    from evaluation.notebook import (
        create_agent_model,
        create_run_directory,
        load_benchmark,
        resolve_run_directory,
    )
    from framework.tools import image_editing_tools

    context = load_benchmark("compbench", prompt_mode="mixed")
    if args.samples_file:
        sample_indices = read_sample_indices(
            _resolve_launch_path(args.samples_file), context.records
        )
    else:
        sample_indices = select_compbench_indices(
            context.records,
            tasks=args.tasks,
            start_index=args.start_index,
            limit=args.limit,
        )
    if not sample_indices:
        raise ValueError("No CompBench annotations match the selected tasks and range.")

    if args.require_cuda:
        import torch

        if not torch.cuda.is_available():
            raise RuntimeError(
                "CUDA is required but PyTorch cannot access a CUDA device. "
                "Check the NVIDIA driver and installed PyTorch build."
            )
        print(f"CUDA GPU: {torch.cuda.get_device_name(0)}")

    if args.resume:
        run_dir = resolve_run_directory(context.output_dir, args.run)
    else:
        run_dir = create_run_directory(context.output_dir)

    print(
        f"Loaded {len(context.records)} CompBench annotations from "
        f"{context.annotation_file}"
    )
    selected_tasks = (
        ", ".join(args.tasks)
        if args.tasks
        else "from sample file" if args.samples_file else "all"
    )
    print(f"Selected tasks: {selected_tasks}")
    print(
        f"Processing {len(sample_indices)} selected annotations "
        f"(first index {sample_indices[0]}, last index {sample_indices[-1]})."
    )
    print(f"Evaluation run: {run_dir}")

    model = create_agent_model()
    tools = image_editing_tools(pool=pool)
    print(f"CompBench agent ready: {model.model_id}")

    first_turn = build_first_turn_config(args, run_dir)
    from_run = build_from_run(args)
    results = run_benchmark(
        context.records,
        sample_indices,
        benchmark="compbench",
        prompt_mode="mixed",
        output_dir=run_dir,
        image_loader=context.image_loader,
        model=model,
        tools=tools,
        resume=args.resume,
        rerun_completed=args.rerun_completed,
        display_fn=None,
        first_turn=first_turn,
        from_run=from_run,
    )

    completed = sum(result["status"] == "completed" for result in results)
    failed = sum(result["status"] == "failed" for result in results)
    print(
        f"CompBench samples: {len(results)} | "
        f"completed: {completed} | failed: {failed}"
    )
    if results:
        mean_runtime = sum(result["elapsed_seconds"] for result in results) / len(
            results
        )
        print(f"Mean runtime: {mean_runtime:.2f}s")
    print(f"Results: {run_dir / 'results' / 'results.jsonl'}")


if __name__ == "__main__":
    main()
